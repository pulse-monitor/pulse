/** 机器的经纬度：优先用精确坐标，否则用国家中心。都没有时返回 null。 */
export function latlon(
  lat: number | null,
  lon: number | null,
  country: string | null,
): [number, number] | null {
  if (lat !== null && lon !== null && Number.isFinite(lat) && Number.isFinite(lon)) {
    return [lat, lon]
  }
  if (!country) return null
  return COUNTRY_LATLON[country.toUpperCase()] ?? null
}
